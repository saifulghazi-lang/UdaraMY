export function getCategoryFromApi(api) {
  if (typeof api !== 'number' || isNaN(api)) return 'moderate';
  if (api <= 50) return 'good';
  if (api <= 100) return 'moderate';
  if (api <= 200) return 'unhealthy';
  if (api <= 300) return 'veryUnhealthy';
  return 'hazardous';
}

export function getCategoryColor(category) {
  switch (category) {
    case 'good': return '#3b82f6';
    case 'moderate': return '#10b981';
    case 'unhealthy': return '#f59e0b';
    case 'veryUnhealthy': return '#ef4444';
    case 'hazardous': return '#881337';
    default: return '#64748b';
  }
}
